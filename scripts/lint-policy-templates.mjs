// Runs every POLICY_TYPES template's default XML through apigeelint, so a
// hand-written policy template that Apigee would reject can never ship again.
// Builds one bundle containing every policy attached to the ProxyEndpoint
// PreFlow, lints it, and attributes each message back to its policy file.
//
//   node scripts/lint-policy-templates.mjs
//
// Exits non-zero if any policy file has an apigeelint *error*.
import { readFileSync } from 'fs';
import { POLICY_TYPES } from '../server/src/lib/policyTemplates.js';
import { lintBundleFiles } from '../server/src/lib/lint.js';
import { generateBundleFiles } from '../server/src/lib/bundleGenerator.js';

// Every policy type needs a name prefix that apigeelint's PO007
// ("policy name should indicate its type") accepts, or every policy the app
// generates warns the moment it's created. apigeelint keeps the accepted
// prefixes per type in plugins/policyMetaData.json under `indications`, so
// they're checked against the real source of truth rather than duplicated.
function checkNamePrefixes() {
  const md = JSON.parse(
    readFileSync(new URL('../node_modules/apigeelint/lib/package/plugins/policyMetaData.json', import.meta.url), 'utf8')
  );
  const namesSrc = readFileSync(new URL('../client/src/lib/policyNames.ts', import.meta.url), 'utf8');
  const prefixes = {};
  for (const m of namesSrc.matchAll(/^  ([A-Za-z0-9]+): '([^']+)',/gm)) prefixes[m[1]] = m[2];

  const problems = [];
  for (const t of POLICY_TYPES) {
    // Mirrors suggestPolicyName: an unmapped type falls back to its own key.
    const prefix = prefixes[t.key] || t.key;
    const indications = md[t.xmlTag || t.key]?.indications || [];
    if (!indications.length) continue;
    const name = `${prefix}-1`.toLowerCase();
    const ok = indications.some((i) => (i.startsWith('^') ? new RegExp(i).test(name) : name.startsWith(i.toLowerCase())));
    if (!ok) problems.push(`      ${t.key.padEnd(26)}"${prefix}-1"  accepted: ${JSON.stringify(indications)}`);
  }
  return problems;
}

const policies = POLICY_TYPES.map((t) => ({
  id: t.key,
  name: t.key,
  type: t.key,
  xml: t.defaultXml(t.key),
}));

const proxy = {
  name: 'template-lintcheck',
  basePath: '/template-lintcheck',
  description: 'Generated by scripts/lint-policy-templates.mjs',
  proxyEndpointName: 'default',
  policies,
  preFlow: { request: policies.map((p) => ({ policyName: p.name })), response: [] },
  postFlow: { request: [], response: [] },
  flows: [],
  routeRules: [{ id: 'rr', name: 'default', targetName: 'default', condition: '' }],
  faultRules: { steps: [] },
  targets: [
    {
      id: 'default',
      name: 'default',
      description: '',
      mode: 'url',
      url: { mode: 'literal', value: 'https://mocktarget.apigee.net' },
      targetServers: [],
      preFlow: { request: [], response: [] },
      postFlow: { request: [], response: [] },
      flows: [],
      faultRules: { steps: [] },
    },
  ],
};

const result = await lintBundleFiles(generateBundleFiles(proxy), 'apiproxy');

if (!result.ok) {
  console.error(`apigeelint could not run: ${result.systemError}`);
  process.exit(2);
}

// Only policy files are this script's business — endpoint-level findings
// (TD002/TD012 and friends) belong to the bundle generator, not a template.
const policyFiles = result.files.filter((f) => f.filePath.includes('/policies/'));
let failed = 0;

// PO007 (policy naming convention) is meaningless here: this script names each
// policy after its type key, whereas the app names them via suggestPolicyName's
// prefixes ("AM-1", "VK-1", ...) at add-time. Filtering it keeps real findings visible.
const IGNORED_RULES = new Set(['PO007']);

for (const file of policyFiles) {
  const messages = file.messages.filter((m) => !IGNORED_RULES.has(m.ruleId));
  const errors = messages.filter((m) => m.severity === 'error');
  const warnings = messages.filter((m) => m.severity === 'warning');
  if (!errors.length && !warnings.length) continue;
  const label = file.filePath.replace('apiproxy/policies/', '').replace('.xml', '');
  console.log(`\n${errors.length ? 'FAIL' : 'warn'}  ${label}`);
  for (const m of [...errors, ...warnings]) {
    console.log(`      ${m.severity.padEnd(7)} ${String(m.ruleId ?? '-').padEnd(7)} ${m.message}`);
  }
  if (errors.length) failed += 1;
}

const prefixProblems = checkNamePrefixes();
if (prefixProblems.length) {
  console.log(`\nFAIL  name prefixes that would trip apigeelint PO007:`);
  prefixProblems.forEach((p) => console.log(p));
}

const clean = POLICY_TYPES.length - policyFiles.length;
console.log(
  `\n${POLICY_TYPES.length} templates linted — ${clean} clean, ` +
    `${policyFiles.length - failed} with warnings only, ${failed} with errors. ` +
    `Name prefixes: ${prefixProblems.length ? `${prefixProblems.length} would warn` : 'all OK'}.`
);
process.exit(failed || prefixProblems.length ? 1 : 0);
